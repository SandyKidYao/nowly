const screens = {
  home: ['assets/home.png', '记录首页：预置心情记录，可以自定义问题、选项和提醒。'],
  answer: ['assets/answer.png', '回答页：此刻，你的心情怎么样？轻点一个选项即可记录。'],
  statistics: ['assets/statistics.png', '统计演示：平均等级、每日趋势和选项占比，使用合成数据。'],
};
const preview = document.querySelector('#preview');
document.querySelectorAll('[data-screen]').forEach(button => {
  button.addEventListener('click', () => {
    const [src, alt] = screens[button.dataset.screen];
    preview.src = src;
    preview.alt = alt;
    document.querySelectorAll('[data-screen]').forEach(tab => tab.setAttribute('aria-pressed', String(tab === button)));
  });
});
// Generated by the release workflow. Downloads follow this exact deployed release.
fetch('release.json').then(response => response.ok ? response.json() : null).then(release => {
  if (!release || !/^v?\d+\.\d+\.\d+(?:-[\w.-]+)?$/.test(release.tag)) return;
  const url = `https://github.com/SandyKidYao/nowly/releases/download/${encodeURIComponent(release.tag)}/nowly.apk`;
  document.querySelectorAll('[data-download]').forEach(link => { link.href = url; });
  document.querySelector('#release-label').textContent = `${release.tag} · Android 8.0+ · 免费开源`;
}).catch(() => {});
